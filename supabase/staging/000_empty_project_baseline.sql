-- Activation definition obtained read-only through MCP, 2026-11-05.
CREATE OR REPLACE FUNCTION public.activate_review_card(p_card_code text, p_activation_code text, p_business_name text, p_review_url text, p_pin text)
 RETURNS boolean
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
DECLARE
  v_code_hash text;
BEGIN
  IF p_card_code IS NULL
     OR p_card_code !~ '^[a-zA-Z0-9_-]{1,30}$'
     OR p_activation_code IS NULL
     OR length(p_activation_code) < 8
     OR length(p_activation_code) > 128
     OR p_business_name IS NULL
     OR length(btrim(p_business_name)) NOT BETWEEN 1 AND 150
     OR p_review_url IS NULL
     OR length(p_review_url) > 2048
     OR p_review_url !~* '^https://(maps\.app\.goo\.gl|www\.google\.com|google\.com|search\.google\.com)/'
     OR p_pin IS NULL
     OR length(p_pin) NOT BETWEEN 6 AND 72
  THEN
    RETURN false;
  END IF;

  SELECT activation_code_hash
  INTO v_code_hash
  FROM public.card_activation
  WHERE card_code = p_card_code
    AND activated_at IS NULL
  FOR UPDATE;

  IF NOT FOUND OR v_code_hash IS NULL THEN
    RETURN false;
  END IF;

  IF v_code_hash <> encode(
    extensions.digest(p_activation_code, 'sha256'),
    'hex'
  ) THEN
    RETURN false;
  END IF;

  UPDATE public.card
  SET business_name = btrim(p_business_name),
      review_url = p_review_url,
      pin_hash = extensions.crypt(
        p_pin,
        extensions.gen_salt('bf')
      )
  WHERE card_code = p_card_code
    AND pin_hash IS NULL;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  UPDATE public.card_activation
  SET activated_at = now()
  WHERE card_code = p_card_code
    AND activated_at IS NULL;

  RETURN true;
END;
$function$

REVOKE ALL ON FUNCTION public.activate_review_card(text,text,text,text,text) FROM PUBLIC, anon, authenticated;


